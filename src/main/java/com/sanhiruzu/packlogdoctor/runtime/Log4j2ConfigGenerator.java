package com.sanhiruzu.packlogdoctor.runtime;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Set;
import java.util.TreeSet;

public final class Log4j2ConfigGenerator {
    public static void generate(Path outputPath, SuppressionConfig config) throws IOException {
        String xml = generateXml(config);
        Files.createDirectories(outputPath.getParent());
        Files.writeString(outputPath, xml, StandardCharsets.UTF_8);
    }

    private static String generateXml(SuppressionConfig config) {
        Set<String> loggerNames = extractLoggerNames(config);
        StringBuilder loggers = new StringBuilder();

        if (loggerNames.isEmpty()) {
            loggers.append("    <!-- No suppressions configured. Edit suppression-config.json to add filters. -->\n");
        } else {
            for (String loggerName : loggerNames) {
                loggers.append("    <Logger name=\"").append(escapeXml(loggerName)).append("\" level=\"OFF\" />\n");
            }
        }

        return """
                <?xml version="1.0" encoding="UTF-8"?>
                <!-- Generated by Pack Log Doctor suppression system -->
                <!-- Usage: Add to Prism Launcher JVM parameters: -Dlog4j.configurationFile=<path-to-this-file> -->
                <!-- The loggers listed below will be suppressed (set to level OFF) when this config is active. -->
                <!-- To modify suppressions, edit pack-log-doctor/suppression-config.json and re-run the game. -->
                <Configuration packages="net.neoforged.fml.logging">
                  <Appenders>
                    <Console name="Console" target="SYSTEM_OUT">
                      <PatternLayout pattern="[%d{HH:mm:ss}] [%t/%l]: %m%n" />
                    </Console>
                  </Appenders>

                  <Loggers>
                """ + loggers + """
                    <Root level="INFO">
                      <AppenderRef ref="Console" />
                    </Root>
                  </Loggers>
                </Configuration>
                """;
    }

    private static Set<String> extractLoggerNames(SuppressionConfig config) {
        Set<String> loggers = new TreeSet<>();
        for (SuppressionConfig.SuppressionRule rule : config.rules()) {
            if (rule.loggerPattern != null && !rule.loggerPattern.isBlank()) {
                loggers.add(rule.loggerPattern);
            }
        }
        return loggers;
    }

    private static String escapeXml(String value) {
        if (value == null) return "";
        return value.replace("&", "&amp;")
                .replace("<", "&lt;")
                .replace(">", "&gt;")
                .replace("\"", "&quot;")
                .replace("'", "&apos;");
    }
}
